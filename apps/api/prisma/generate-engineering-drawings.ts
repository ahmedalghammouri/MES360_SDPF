// Tracker IDs 25 and 26: the production-line instrumentation layout and the
// automation system architecture.
//
// Generated from `machines`, `devices` and `tag_definitions` rather than drawn
// by hand. A hand-drawn diagram is out of date the first time somebody re-binds
// a tag, and then it is worse than no diagram: it is a document that says the
// wrong thing with authority. Re-run this after any I/O change.
//
//   npx ts-node --transpile-only prisma/generate-engineering-drawings.ts
//   DATABASE_URL="…/mes360…" FACTORY=SDPF npx ts-node …   # pick the factory
//
// Output: docs/NCC-25-Instrumentation-Layout.html
//         docs/NCC-26-Automation-Architecture.html
